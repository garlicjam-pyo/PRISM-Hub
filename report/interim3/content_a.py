BL("모델은 실제 상태를 강제로 자르지 않는다. 제어기는 지령만 제한하므로 과부하나 지연으로 생기는 정격 위반이 그대로 드러난다.")
BL("실패한 사례는 지우지 않고 회귀 시험으로 남긴다. 모델 사이의 차이(에지 양자화, 추가 소자, 해석기 특성)는 결과와 함께 명시한다.")
BL("소자 수준 회로 모델은 검증 단계마다 새 테스트벤치를 만들어 남기고, 같은 조건의 검증 모델 결과를 기준값으로 둔다.")
