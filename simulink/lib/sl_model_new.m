function mdl = sl_model_new(mdl, initScript)
%SL_MODEL_NEW  테스트벤치 모델을 새로 만들고 공통 해석기 설정을 적용한다.
%
%   mdl = sl_model_new('TB01_StageA_RSC', 'TB01_init.m')
%
%   - 같은 이름의 모델이 열려 있으면 저장하지 않고 닫는다(빌드 스크립트가 항상 처음부터 다시 만든다).
%   - Simulink 해석기: 고정 간격 이산(FixedStepDiscrete), 간격 TB.dt.
%     연속 상태는 모두 Simscape 지역 해석기(Solver Configuration)가 맡으므로 Simulink 쪽 연속 상태는 없다.
%   - InitFcn: 모델 파일과 같은 폴더의 초기화 스크립트(initScript)를 실행해 기본 작업공간에 P, TB를 만든다.
%     따라서 모델 파일만 열어 실행해도 파라미터가 준비된다.

if bdIsLoaded(mdl), close_system(mdl, 0); end
new_system(mdl);
set_param(mdl, ...
    'SolverType', 'Fixed-step', ...
    'Solver', 'FixedStepDiscrete', ...
    'FixedStep', 'TB.dt', ...
    'StartTime', '0', ...
    'StopTime', 'TB.t_end', ...
    'ReturnWorkspaceOutputs', 'on', ...
    'SaveTime', 'off', 'SaveOutput', 'off', 'SaveState', 'off', ...
    'SignalLogging', 'off', ...
    'SimscapeLogType', 'none');
init = sprintf(['%% 모델과 같은 폴더의 초기화 스크립트를 실행해 P(설계 파라미터)와 TB(시험 조건)를 만든다.\n' ...
                'run(fullfile(fileparts(get_param(bdroot, ''FileName'')), ''%s''));'], initScript);
set_param(mdl, 'InitFcn', init);
end
